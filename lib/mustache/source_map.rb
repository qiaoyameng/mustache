require 'mustache/parser'

class Mustache

  # Mustache::SourceMap powers `Mustache#render_with_map`. It renders a
  # template exactly like `Mustache#render` does, but additionally
  # records which fragment of the main template, of a partial, or of a
  # lambda-generated template produced each byte of the output.
  #
  # The result of `render_with_map` is a two element array: the
  # rendered string (byte-identical to what `render` returns) and an
  # array of SourceMap::Segment objects whose ranges completely cover
  # the output.
  class SourceMap

    # The identity of a source a Segment points to.
    #
    # A source is one of:
    #
    # * the main template (named after its template file, template
    #   name, or "(inline template)"),
    # * a partial, named after the partial and carrying the chain of
    #   partials through which it was included,
    # * a template generated by a lambda at render time. These are
    #   `dynamic?` and their offsets refer to the generated source,
    #   never to lines of a template file.
    class Source
      attr_reader :name, :text, :call_chain

      def initialize(name, text, call_chain = [], dynamic = false)
        @name = name
        @text = text
        @call_chain = call_chain
        @dynamic = dynamic
      end

      # Dynamic sources are generated at render time by lambdas.
      def dynamic?
        @dynamic
      end

      def ==(other)
        other.is_a?(Source) &&
          name == other.name &&
          call_chain == other.call_chain &&
          dynamic? == other.dynamic?
      end
      alias_method :eql?, :==

      def hash
        [name, call_chain, dynamic?].hash
      end

      # Converts a byte offset into this source into a 1-based
      # [line, column] pair. The column is counted in bytes.
      def line_and_column(offset)
        line = 1
        column = 0
        @text.to_s.bytes.each_with_index do |byte, index|
          break if index >= offset
          if byte == 10 # "\n"
            line += 1
            column = 0
          else
            column += 1
          end
        end
        [line, column]
      end
    end

    # A Segment maps a byte range of the rendered output to the source
    # fragment it originates from.
    #
    # The `kind` is one of:
    #
    # * :static      - literal template text
    # * :etag        - output of an escaped {{variable}} tag
    # * :utag        - output of an unescaped {{{variable}}} / {{&variable}} tag
    # * :indentation - indentation inserted by a standalone {{>partial}} tag
    #
    # `range` is a byte range (exclusive end) into the rendered output,
    # `source` is the SourceMap::Source the bytes originate from and
    # `offset` is the byte offset into that source. For :indentation
    # segments the source is the template holding the {{>partial}} tag
    # and the offset points at that tag.
    #
    # `value` is nil unless `render_with_map` was called with
    # `record_values: true`.
    class Segment
      attr_reader :kind, :range, :source, :offset, :value

      def initialize(kind, range, source, offset, value = nil)
        @kind = kind
        @range = range
        @source = source
        @offset = offset
        @value = value
      end

      # Length of the segment in output bytes.
      def length
        @range.end - @range.begin
      end
    end

    # Maps byte offsets of an indented partial source (the result of
    # `source.gsub(/^/, indentation)` performed for standalone partial
    # tags) back to the original partial source, and splits static
    # text into the partial's own text and the inserted indentation.
    class PartialMapping
      def initialize(indented_source, indentation, source, parent_source, tag_offset)
        @indentation_length = indentation.bytesize
        @line_starts = compute_line_starts(indented_source)
        @source = source
        @parent_source = parent_source
        @tag_offset = tag_offset
      end

      # Maps a byte offset in the indented source back to the
      # corresponding byte offset in the original partial source.
      def map_offset(position)
        position - @indentation_length * (line_index(position) + 1)
      end

      # Splits a static token starting at byte `position` of the
      # indented source into [kind, source, offset, text] pieces,
      # separating inserted indentation from the partial's own text.
      def pieces(text, position)
        chunks = []
        cursor = 0
        length = text.bytesize

        each_indentation_interval(position, length) do |from, to|
          if from > cursor
            chunks << [:static, @source, map_offset(position + cursor), text.byteslice(cursor...from)]
          end
          chunks << [:indentation, @parent_source, @tag_offset, text.byteslice(from...to)]
          cursor = to
        end

        if cursor < length
          chunks << [:static, @source, map_offset(position + cursor), text.byteslice(cursor...length)]
        end

        chunks
      end

      private

      def compute_line_starts(source)
        binary = source.b
        starts = [0]
        index = -1
        while index = binary.index("\n".b, index + 1)
          starts << index + 1
        end
        starts
      end

      def line_index(position)
        index = @line_starts.bsearch_index { |start| start > position }
        (index || @line_starts.length) - 1
      end

      def each_indentation_interval(position, length)
        @line_starts.each do |start|
          next if start < position
          break if start >= position + length
          from = start - position
          to = [from + @indentation_length, length].min
          yield from, to
        end
      end
    end

    # Interprets parsed Mustache tokens, mirroring the semantics of
    # Mustache::Generator exactly, while recording a segment for every
    # run of output bytes. Each context lookup and each lambda is
    # evaluated exactly once.
    class Renderer
      def initialize(options = {})
        @record_values = options[:record_values]
      end

      # Renders `source_string` against `context` and returns
      # [output, segments]. `source` is the SourceMap::Source identity
      # of `source_string`.
      def render(source_string, context, source, parser_options = {}, delims = nil)
        @output = +""
        @segments = []
        render_exp(parse(source_string, parser_options, delims), context, source, nil)
        [@output, merge(@segments)]
      end

      private

      def parse(source_string, parser_options, delims = nil)
        parser = Parser.new((parser_options || {}).merge(:record_positions => true))
        if delims
          parser.otag, parser.ctag = delims
        end
        parser.compile(source_string)
      end

      def render_exp(exp, context, source, mapping)
        case exp[0]
        when :multi
          exp[1..-1].each { |e| render_exp(e, context, source, mapping) }
        when :static
          emit_static(exp[1], exp[2], source, mapping)
        when :mustache
          render_mustache(exp, context, source, mapping)
        end
      end

      def render_mustache(exp, context, source, mapping)
        case exp[1]
        when :etag
          names = exp[2][2]
          value = fetch(context, names)
          if value.is_a?(Proc)
            value, = render_dynamic(value.call.to_s, context, nil, names, source)
          end
          emit(:etag, context.escape(value), source, map_pos(exp[4], mapping), value)
        when :utag
          names = exp[2][2]
          value = fetch(context, names)
          if value.is_a?(Proc)
            rendered, segments = render_dynamic(value.call.to_s, context, nil, names, source)
            append_rendered(rendered, segments)
          else
            emit(:utag, value.to_s, source, map_pos(exp[4], mapping), value)
          end
        when :section
          render_section(exp, context, source, mapping)
        when :inverted_section
          value = fetch(context, exp[2][2])
          if value.nil? || value == false || (value.class != String && value.respond_to?(:empty?) && value.empty?)
            render_exp(exp[4], context, source, mapping)
          end
        when :partial
          render_partial(exp[2], exp[4], map_pos(exp[5], mapping), context, source)
        end
      end

      def render_section(exp, context, source, mapping)
        names = exp[2][2]
        content = exp[4]
        value = fetch(context, names)

        case value
        when NilClass, FalseClass
          # Nothing to render.
        when TrueClass
          render_exp(content, context, source, mapping)
        when Proc
          rendered, segments = render_dynamic(value.call(exp[5]).to_s, context, exp[6], names, source)
          append_rendered(rendered, segments)
        when Array, Enumerator, Mustache::Enumerable
          value.each do |item|
            context.push(item)
            begin
              render_exp(content, context, source, mapping)
            ensure
              context.pop
            end
          end
        else
          context.push(value)
          begin
            render_exp(content, context, source, mapping)
          ensure
            context.pop
          end
        end
      end

      def render_partial(name, indentation, position, context, source)
        mustache = context.mustache_in_stack
        original = mustache.partial(name.to_sym).to_s
        partial_source = Source.new(name.to_s, original, source.call_chain + [name.to_sym])

        if indentation.empty?
          render_exp(parse(original, {}), context, partial_source, nil)
        else
          indented = original.gsub(/^/, indentation)
          mapping = PartialMapping.new(indented, indentation, partial_source, source, position)
          render_exp(parse(indented, {}), context, partial_source, mapping)
        end
      end

      # Renders a template generated by a lambda. The generated source
      # gets its own dynamic Source identity so its offsets are never
      # confused with lines of a template file.
      def render_dynamic(source_string, context, delims, names, source)
        dynamic = Source.new("lambda:#{names.join('.')}", source_string, source.call_chain, true)
        renderer = Renderer.new(:record_values => @record_values)
        renderer.render(source_string, context.dup, dynamic, {}, delims)
      end

      def fetch(context, names)
        return context.current if names.empty?

        initial, *rest = names.map { |name| name.to_sym }
        rest.reduce(context[initial]) do |value, key|
          value && context.find(value, key)
        end
      end

      def emit_static(text, position, source, mapping)
        if mapping
          mapping.pieces(text, position).each do |kind, piece_source, offset, slice|
            emit(kind, slice, piece_source, offset)
          end
        else
          emit(:static, text, source, position)
        end
      end

      def emit(kind, text, source, offset, value = nil)
        return if text.bytesize == 0

        start = @output.bytesize
        @output << text
        value = nil unless @record_values
        @segments << Segment.new(kind, start...(start + text.bytesize), source, offset, value)
      end

      def append_rendered(string, segments)
        base = @output.bytesize
        @output << string
        segments.each do |segment|
          range = (base + segment.range.begin)...(base + segment.range.end)
          @segments << Segment.new(segment.kind, range, segment.source, segment.offset, segment.value)
        end
      end

      def map_pos(position, mapping)
        mapping ? mapping.map_offset(position) : position
      end

      # Merges adjacent static segments that point at consecutive
      # bytes of the same source. The merged table still covers the
      # whole output.
      def merge(segments)
        segments.each_with_object([]) do |segment, merged|
          last = merged.last
          if last && mergeable?(last, segment)
            merged[-1] = Segment.new(:static, last.range.begin...segment.range.end,
                                     last.source, last.offset, last.value)
          else
            merged << segment
          end
        end
      end

      def mergeable?(first, second)
        first.kind == :static && second.kind == :static &&
          first.source == second.source &&
          first.range.end == second.range.begin &&
          first.offset && second.offset &&
          first.offset + first.length == second.offset
      end
    end
  end

  # Instantiates an instance of this class and calls
  # `render_with_map` with the passed args.
  def self.render_with_map(*args, **kwargs)
    new.render_with_map(*args, **kwargs)
  end

  # Renders a template exactly like #render, but returns a two element
  # array of the rendered string and a source map: an array of
  # Mustache::SourceMap::Segment whose byte ranges completely cover
  # the output and point back to the template, partial, or
  # lambda-generated source fragment each run of bytes originates
  # from.
  #
  # Lookups and lambdas are evaluated exactly once, just like #render.
  # Variable values are not recorded unless `record_values: true` is
  # passed.
  #
  # @example Render a string template with a source map
  #   output, map = Mustache.render_with_map("Hi {{thing}}!", :thing => "world")
  #   map.first.kind  # => :static
  #   map.first.range # => 0...3
  #
  # @param [String,Hash] data A String template or a Hash context.
  # @param [Hash] ctx A Hash context if `data` is a String template.
  # @param [Boolean] record_values Record variable values on segments.
  # @return [Array(String, Array<Mustache::SourceMap::Segment>)]
  def render_with_map(data = template, ctx = {}, record_values: false, **extra)
    case data
    when Hash
      ctx = data
    when Symbol
      self.template_name = data
    end
    ctx = ctx.merge(extra) unless extra.empty?

    tpl = case data
    when Hash
      templateify(template)
    when Symbol
      templateify(template)
    else
      templateify(data)
    end

    source = SourceMap::Source.new(source_map_source_name(data), tpl.source)
    renderer = SourceMap::Renderer.new(:record_values => record_values)

    return renderer.render(tpl.source, context, source, tpl.options) if ctx == {}

    begin
      context.push(ctx)
      renderer.render(tpl.source, context, source, tpl.options)
    ensure
      context.pop
    end
  end

  private

  # The source identity used for the main template in a source map.
  def source_map_source_name(data)
    if data.is_a?(String)
      "(inline template)"
    else
      template_file || template_name
    end
  end
end
